// src/unicode/<version>/emoji-test.txt から src/data/<version>.ts と src/versions.ts を生成する
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { parseEmojiTest } from "../src/parser.ts";

const root = join(import.meta.dirname, "..", "src");
const versions = readdirSync(join(root, "unicode"))
  .filter((v) => /^\d+\.\d+$/.test(v))
  .sort((a, b) => Number(a) - Number(b));

mkdirSync(join(root, "data"), { recursive: true });

for (const version of versions) {
  const data = parseEmojiTest(readFileSync(join(root, "unicode", version, "emoji-test.txt"), "utf8"));
  if (data.version !== version) throw new Error(`Directory ${version} contains data for ${data.version}`);

  const groups = data.groups.map(([name, emojis]) => `  [${JSON.stringify(name)}, [\n${emojis.map((e) => `    ${JSON.stringify(e)},`).join("\n")}\n  ]],`);
  writeFileSync(
    join(root, "data", `${version}.ts`),
    `// Generated by scripts/generate-data.ts from src/unicode/${version}/emoji-test.txt. Do not edit.\nimport type { EmojiData } from "../types";\n\nconst data: EmojiData = { version: ${JSON.stringify(version)}, groups: [\n${groups.join("\n")}\n] };\n\nexport default data;\n`,
  );

  const count = data.groups.reduce((n, [, e]) => n + e.length, 0);
  const variants = data.groups.reduce((n, [, e]) => n + e.reduce((m, x) => m + (x[2]?.length ?? 0), 0), 0);
  console.log(`${version}: ${count} emojis, ${variants} skin tone variants`);
}

writeFileSync(
  join(root, "versions.ts"),
  `// Generated by scripts/generate-data.ts. Do not edit.
export const UNICODE_VERSIONS = ${JSON.stringify(versions)} as const;

export type UnicodeVersion = (typeof UNICODE_VERSIONS)[number];

export const LATEST_UNICODE_VERSION: UnicodeVersion = ${JSON.stringify(versions.at(-1))};
`,
);

writeFileSync(
  join(root, "loaders.ts"),
  `// Generated by scripts/generate-data.ts. Do not edit.
import type { EmojiData } from "./types";
import type { UnicodeVersion } from "./versions";

// Metro は動的 import のパスを静的に解決する必要があるため、バージョンごとに列挙する。
// ここから参照される全バージョンがバンドルに含まれるので、メインのエントリポイントからは import しないこと
export const loaders: Record<UnicodeVersion, () => Promise<{ default: EmojiData }>> = {
${versions.map((v) => `  ${JSON.stringify(v)}: () => import("./data/${v}"),`).join("\n")}
};
`,
);
